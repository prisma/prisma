import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import postgresAdapter from '@internal/adapter-postgres/control';
import { createControlClient } from '@internal/cli/control-api';
import postgresDriver from '@internal/driver-postgres/control';
import sql from '@internal/family-sql/control';
import { emitContractSpaceArtifacts } from '@internal/migration-tools/spaces';
import postgres from '@internal/target-postgres/control';
import { createDevDatabase, timeouts, withClient } from '@repo/test-utils';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import supabasePack from '../src/exports/pack';
import contractJson from './fixtures/example-app/contract.json' with { type: 'json' };
import { setUpSupabaseMockSchema } from './fixtures/supabase-reference/set-up-mock-schema';

const TEST_INVOCATION = { cwd: process.cwd(), configPath: undefined, dbGiven: false };

async function initExampleApp(connectionString: string, migrationsDir: string): Promise<void> {
  await withClient(connectionString, async (client) => {
    await setUpSupabaseMockSchema(client);
  });
  const space = supabasePack.contractSpace;
  if (!space) {
    throw new Error('supabasePack must declare a contractSpace');
  }
  await emitContractSpaceArtifacts(migrationsDir, 'supabase', {
    contract: space.contractJson,
    contractDts: '// supabase extension contract space\n',
    headRef: { hash: space.headRef.hash, invariants: [...space.headRef.invariants] },
  });
  const client = createControlClient({
    family: sql,
    target: postgres,
    adapter: postgresAdapter,
    driver: postgresDriver,
    extensions: [supabasePack],
  });
  try {
    await client.connect(connectionString);
    const result = await client.dbInit({
      invocation: TEST_INVOCATION,
      contract: contractJson,
      mode: 'apply',
      migrationsDir,
    });
    if (!result.ok) {
      throw new Error(`db init apply failed: ${result.failure.message}`);
    }
  } finally {
    await client.close();
  }
}

describe('Profile.id in the example app', () => {
  let database: Awaited<ReturnType<typeof createDevDatabase>>;
  let migrationsDir: string;

  beforeEach(async () => {
    database = await createDevDatabase();
    migrationsDir = await mkdtemp(join(tmpdir(), 'supabase-profile-id-'));
  }, timeouts.spinUpPpgDev);

  afterEach(async () => {
    if (database) await database.close();
    if (migrationsDir) await rm(migrationsDir, { recursive: true, force: true });
  }, timeouts.spinUpPpgDev);

  it(
    'is generated by the database for an insert that does not go through the Prisma client',
    async () => {
      const { connectionString } = database;
      await initExampleApp(connectionString, migrationsDir);

      const userId = crypto.randomUUID();
      const inserted = await withClient(connectionString, async (pg) => {
        await pg.query(
          'INSERT INTO auth.users (id, email, created_at, updated_at) VALUES ($1, $2, now(), now())',
          [userId, `${userId}@example.com`],
        );
        const result = await pg.query<{ id: string }>(
          'INSERT INTO public.profile (username, "userId") VALUES ($1, $2) RETURNING id',
          ['alice', userId],
        );
        return result.rows;
      });

      expect(inserted).toEqual([
        {
          id: expect.stringMatching(
            /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[0-9a-f]{4}-[0-9a-f]{12}$/,
          ),
        },
      ]);
    },
    timeouts.spinUpPpgDev * 2,
  );
});
